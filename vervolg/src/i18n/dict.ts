/**
 * The bilingual surface.
 *
 * Dutch is the default: the product exists because a Groningen coach cannot
 * remember what was agreed nine months ago, and that coach reads Dutch. English
 * is a mirror, not a replacement — a reviewer or a jury should be able to read
 * every screen without touching the artefacts the spec requires to be Dutch
 * (§8.3 "One A4 page, in Dutch"; §6.1 the household view is B1 Dutch; §7.2 the
 * extractor is a rules engine over Dutch text).
 *
 * THE FIXTURES ARE PART OF THE ARGUMENT, NOT A TRANSLATION PROBLEM.
 * "Kwijtschelding aanvragen" is a real Dutch municipal tax-relief scheme; the
 * whole gate exists because "Ze heeft COPD" is a sentence a coach writes about
 * a person. Translate that and the demo stops being about the Netherlands.
 * So the UI chrome is translatable and the dossier content is not. When English
 * is active, the screens that render dossier content carry a visible line
 * saying so rather than silently mixing languages.
 */

export type Locale = "nl" | "en";
export const DEFAULT_LOCALE: Locale = "nl";
export const LOCALES: Locale[] = ["nl", "en"];
export const LOCALE_COOKIE = "vervolg-locale";

export function isLocale(v: string | undefined | null): v is Locale {
  return v === "nl" || v === "en";
}

export function parseLocale(v: string | undefined | null): Locale {
  return isLocale(v) ? v : DEFAULT_LOCALE;
}

