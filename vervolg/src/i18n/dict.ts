export const DICTS: Record<Locale, Record<DictKey, string>> = { nl, en };

/** Replace `{name}` placeholders. Missing values are left visible, not blanked. */
export function interpolate(s: string, vars?: Record<string, string | number>): string {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

/** The function components actually call. */
export function t(locale: Locale, key: DictKey, vars?: Record<string, string | number>): string {
  return interpolate(DICTS[locale][key] ?? DICTS.nl[key] ?? key, vars);
}

